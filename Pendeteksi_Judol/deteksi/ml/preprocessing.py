VOWELS = set("aiueo")

def rejoin_split_letters(tokens: List[str]) -> List[str]:
    out, i, n = [], 0, len(tokens)
    while i < n:
        j, letters = i, []
        # gabungkan huruf terpisah: p u l a u → pulau
        while j < n and re.fullmatch(r'[A-Za-z]', tokens[j]):
            letters.append(tokens[j].lower())
            j += 1
        if len(letters) >= 3:
            word = ''.join(letters)
            # kalau setelah huruf terpisah ada digit, gabungkan: p u l a u 7 7 7 → pulau777
            k, digits = j, []
            while k < n and re.fullmatch(r'\d+', tokens[k]):
                digits.append(tokens[k]); k += 1
            if digits:
                word += ''.join(digits)
                j = k
            if any(ch in VOWELS for ch in word) and 3 <= len(word) <= 24:
                out.append(word)
                i = j
                continue

        # blok digit murni
        if re.fullmatch(r'\d+', tokens[i]):
            k, digits = i, []
            while k < n and re.fullmatch(r'\d+', tokens[k]):
                digits.append(tokens[k]); k += 1
            digits_str = ''.join(digits)
            out.append(digits_str)
            i = k
            continue

        # default: token lain lewat saja
        out.append(tokens[i])
        i += 1

    return out

