"""6) Intraword symbols handling"""

_PUNCT_MIDWORD = r"[',.!?\u2026;]+"

def _allowed_chars(keep_at: bool) -> str:
    return r"@._\-" if keep_at else r"._\-"

def handle_intraword_symbols(text: str, *, keep_at: bool = True) -> str:
    allowed = _allowed_chars(keep_at)

    # punctuation di tengah kata/angka → spasi
    text = re.sub(rf"(?iu)(?<=\w){_PUNCT_MIDWORD}(?=\w)", " ", text)

    # karakter aneh yang bukan huruf/angka/allowed diapit non boundary → spasi
    text = re.sub(rf"(?iu)[^\w{allowed}\s]+", " ", text)

    return re.sub(r"\s+", " ", text).strip()

